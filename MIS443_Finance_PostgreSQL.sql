BEGIN;

DROP TABLE IF EXISTS public.transactions;
DROP TABLE IF EXISTS public.accounts;
DROP TABLE IF EXISTS public.branches;
DROP TABLE IF EXISTS public.customers;

CREATE TABLE public.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    first_name  VARCHAR(50) NOT NULL,
    last_name   VARCHAR(50) NOT NULL,
    city        VARCHAR(50) NOT NULL,
    state       CHAR(2) NOT NULL,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT chk_customer_state CHECK (char_length(state) = 2)
);

CREATE TABLE public.branches (
    branch_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    branch_name VARCHAR(50) NOT NULL,
    city        VARCHAR(50) NOT NULL,
    state       CHAR(2) NOT NULL,
    CONSTRAINT pk_branches PRIMARY KEY (branch_id),
    CONSTRAINT chk_branch_state CHECK (char_length(state) = 2)
);

CREATE TABLE public.accounts (
    account_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    customer_id  INTEGER NOT NULL,
    branch_id    INTEGER NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    balance      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (account_id),
    CONSTRAINT fk_accounts_customer
        FOREIGN KEY (customer_id) REFERENCES public.customers (customer_id),
    CONSTRAINT fk_accounts_branch
        FOREIGN KEY (branch_id) REFERENCES public.branches (branch_id),
    CONSTRAINT chk_account_type
        CHECK (account_type IN ('Checking', 'Savings', 'Credit Card'))
);

CREATE TABLE public.transactions (
    transaction_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_id       INTEGER NOT NULL,
    transaction_date DATE NOT NULL,
    amount           NUMERIC(12, 2) NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (transaction_id),
    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id) REFERENCES public.accounts (account_id),
    CONSTRAINT chk_transaction_amount CHECK (amount <> 0)
);

